/* Run with the built frontend served by FastAPI: node tests/test_product_e2e.cjs.
   Uses synthetic demo accounts; creates and settles a test obligation. */
const {chromium}=require('../frontend/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=process.env.E2E_BASE_URL||'http://127.0.0.1:8000';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 page.setDefaultTimeout(110000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/cabinet/');
 await page.locator('[data-login]').waitFor({state:'visible'});
 await page.screenshot({path:'docs/screenshots/login.png',fullPage:true});
 await page.locator('[data-login-as="ip"]').click();
 await page.locator('.catalog-card').first().waitFor();
 assert.equal(await page.locator('.catalog-card').count(),18);
 await page.screenshot({path:'docs/screenshots/overview.png',fullPage:true});
 await page.goto(base+'/cabinet/new/');
 await page.waitForFunction(()=>document.querySelector('[name="inn"]').value.length===12);
 await page.locator('[name="amount"]').fill('600000');
 await page.locator('[name="goal"]').fill('E2E: оборудование для мастерской');
 await page.locator('[data-wizard-next]').click();
 await page.locator('[data-wizard-next]').click();
 await page.locator('[name="scenario"]').selectOption('overdue');
 await page.locator('[data-attach]').click();
 await page.locator('[data-attached]').waitFor({state:'visible'});
 await page.locator('[data-wizard-next]').click();
 await page.locator('[data-calculate]').click();
 await page.locator('[data-assessment]').waitFor({state:'visible'});
 const assessmentUrl=page.url();
 await page.reload();
 await page.locator('[data-assessment]').waitFor({state:'visible'});
 assert.equal(page.url(),assessmentUrl);
 assert.equal(await page.locator('[name="amount"]').inputValue(),'600000');
 await page.screenshot({path:'docs/screenshots/assessment.png',fullPage:true});
 await page.locator('[data-consent]').check();
 await page.locator('[data-submit-application]').click();
 await page.waitForURL('**/cabinet/application/**');
 await page.locator('[data-detail] .detail-columns').waitFor();
 const id=new URL(page.url()).searchParams.get('id');
 assert(id);
 await page.screenshot({path:'docs/screenshots/application.png',fullPage:true});
 await page.locator('[data-logout]').click();
 await page.locator('[data-login-as="bank"]').waitFor({state:'visible'});
 await page.locator('[data-login-as="bank"]').click();
 await page.locator('[data-table] table').waitFor();
 await page.screenshot({path:'docs/screenshots/bank.png',fullPage:true});
 await page.goto(base+'/cabinet/application/?id='+id);
 await page.locator('[data-comment]').fill('E2E: сотрудник проверил синтетические основания');
 await page.locator('[data-action="approve"]').click();
 await page.locator('[data-action="sign"]').first().waitFor();
 await page.locator('[data-comment]').fill('E2E: проверяем отказ учебного оформления');
 await page.locator('[data-action="sign"][data-failure]').click();
 await page.getByText('Ошибка симуляции оформления',{exact:true}).waitFor();
 await page.locator('[data-comment]').fill('E2E: учебное оформление подтверждено');
 await page.locator('[data-action="sign"]').first().click();
 await page.locator('[data-action="pay"]').first().waitFor();
 await page.locator('[data-comment]').fill('E2E: проверяем симуляцию ошибки выплаты');
 await page.locator('[data-failure]').click();
 await page.getByText('Симуляция ошибки выплаты',{exact:true}).waitFor();
 await page.locator('[data-comment]').fill('E2E: повторная симуляция успешной выплаты');
 await page.locator('[data-action="pay"]').first().click();
 await page.locator('[data-detail] .status-funded').first().waitFor();
 await page.locator('[data-comment]').fill('E2E: синтетическое обязательство погашено');
 await page.locator('[data-action="settle"]').click();
 await page.locator('[data-detail] .status-settled').first().waitFor();
 await page.goto(base+'/cabinet/assistant/');
 await page.locator('[data-chat-form]').waitFor();
 // The E2E suite validates UI without requiring paid model access.
 await page.route('**/api/v1/chat',route=>route.request().method()==='POST'?route.fulfill({json:{text:'Тестовый ответ помощника',mode:'rules',model:null,questions:[{text:'Какая цель финансирования?',options:['Оборудование','Запасы']}]}}):route.continue());
 await page.locator('[name="message"]').fill('Помоги выбрать финансирование');
 await page.locator('[data-chat-form] button').click();
 await page.locator('.chat-bubble').filter({hasText:'Тестовый ответ помощника'}).waitFor();
 await page.locator('.chat-bubble').filter({hasText:'Какая цель финансирования?'}).waitFor();
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto(base+'/cabinet/');
 await mobile.locator('[data-login]').waitFor({state:'visible'});
 assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await mobile.screenshot({path:'docs/screenshots/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'passed',application:id,checks:['demo login','18 products','scenario assessment','submission','staff approval','payment failure and retry','settlement','chat question UI','mobile width','no JavaScript errors']}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
